            all: ['all', '', 'hamısı', 'hamisi'],
            '': ['all', '', 'hamısı', 'hamisi'],
            hamısı: ['all', '', 'hamısı', 'hamisi'],
            hamisi: ['all', '', 'hamısı', 'hamisi'],
            telefon: ['telefon', 'phone', 'telefonlar'],
